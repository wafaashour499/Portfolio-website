const reverseTranslations = {};
for (const [en, ar] of Object.entries(translations)) {
    reverseTranslations[ar] = en;
}

let currentLang = 'en';

function normalizeText(text) {
    return text.replace(/\s+/g, ' ').trim();
}

function toggleLanguage() {
    currentLang = currentLang === 'en' ? 'ar' : 'en';
    const targetMap = currentLang === 'ar' ? translations : reverseTranslations;

    // Update layout direction
    document.documentElement.dir = currentLang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = currentLang;

    // Update document title
    if (currentLang === 'ar') {
        document.title = "الوفاء عاشور | محلل بيانات ومهندس ذكاء اصطناعي وأتمتة";
    } else {
        document.title = "Alwafa Ashour | Data Analyst & AI Automation Engineer";
    }

    // Update font family class
    if (currentLang === 'ar') {
        document.body.classList.add('arabic-font');
    } else {
        document.body.classList.remove('arabic-font');
    }

    // Traverse all text nodes
    const walk = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
    let n;
    const nodesToUpdate = [];
    while (n = walk.nextNode()) {
        // Skip script and style tags
        if (n.parentNode && (n.parentNode.nodeName === 'SCRIPT' || n.parentNode.nodeName === 'STYLE')) {
            continue;
        }

        const text = normalizeText(n.nodeValue);
        if (text && targetMap[text]) {
            nodesToUpdate.push({ node: n, newText: targetMap[text], oldText: text });
        }
    }

    nodesToUpdate.forEach(({ node, newText }) => {
        // Replace inner content but preserve leading/trailing whitespace
        const match = node.nodeValue.match(/^(\s*)([\s\S]*?)(\s*)$/);
        if (match) {
            node.nodeValue = match[1] + newText + match[3];
        } else {
            node.nodeValue = newText;
        }
    });

    // Update placeholders
    const inputs = document.querySelectorAll('[placeholder]');
    inputs.forEach(input => {
        const ph = normalizeText(input.getAttribute('placeholder') || '');
        if (targetMap[ph]) {
            input.setAttribute('placeholder', targetMap[ph]);
        }
    });

    // Update button text
    const langBtn = document.getElementById('lang-toggle');
    if (langBtn) {
        langBtn.textContent = currentLang === 'en' ? 'AR' : 'EN';
    }
}

document.addEventListener('DOMContentLoaded', () => {
    const langBtn = document.getElementById('lang-toggle');
    if (langBtn) {
        langBtn.addEventListener('click', toggleLanguage);
    }
});
